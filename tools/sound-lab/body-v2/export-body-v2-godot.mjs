import {readFileSync,writeFileSync,mkdirSync,copyFileSync,readdirSync,existsSync} from 'node:fs';
import {join,resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const lab=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const source=join(lab,'profiles','platform-body-v2');
const game=resolve(process.argv[2]||join(lab,'..','train-game'));
const dest=join(game,'assets/sounds/body_v2');mkdirSync(dest,{recursive:true});
const sha=b=>createHash('sha256').update(b).digest('hex');
const expected=JSON.parse(readFileSync(join(source,'provenance.json'),'utf8'));
const padFrames=48000*2;
for(const name of [...Array.from({length:8},(_,i)=>`impact-${i}`),'rolling-bed']){
 const raw=readFileSync(join(source,`${name}.wav`));
 if(sha(raw)!==expected.hashes[`${name}.wav`])throw Error(`Approved source changed: ${name}`);
 if(raw.toString('ascii',36,40)!=='data'||raw.readUInt16LE(22)!==1||raw.readUInt32LE(24)!==48000||raw.readUInt16LE(34)!==16)throw Error('Unexpected source WAV');
 copyFileSync(join(source,`${name}.wav`),join(dest,`${name}.wav`));
 const frames=raw.readUInt32LE(40)/2,padding=name==='rolling-bed'?0:padFrames;
 for(let channel=0;channel<2;channel++){
  const out=Buffer.alloc(44+(frames+padding)*4);raw.copy(out,0,0,44);
  out.writeUInt32LE(out.length-8,4);out.writeUInt16LE(2,22);out.writeUInt32LE(48000*4,28);out.writeUInt16LE(4,32);out.writeUInt32LE(out.length-44,40);
  for(let i=0;i<frames;i++)out.writeInt16LE(raw.readInt16LE(44+i*2),44+(i+padding)*4+channel*2);
  writeFileSync(join(dest,`${name}-${channel?'right':'left'}.wav`),out);
 }
}
for(const name of readdirSync(dest).filter(x=>x.endsWith('.wav'))){
 const path=join(dest,name+'.import');
 let text=existsSync(path)?readFileSync(path,'utf8'):'[remap]\nimporter="wav"\ntype="AudioStreamWAV"\n\n[params]\ncompress/mode=0\nedit/trim=false\nedit/normalize=false\n';
 text=text.replace(/compress\/mode=\d+/,'compress/mode=0');
 writeFileSync(path,text);
}
writeFileSync(join(dest,'provenance.json'),JSON.stringify(expected,null,2)+'\n');
writeFileSync(join(game,'game/body_v2_data.gd'),`extends RefCounted
## GENERATED by railway-clang-simulator/tools/export-body-v2-godot.mjs.
## Approved mono PCM is unchanged; L/R copies route channels and pad future starts.
const MODEL_ID := "platform-body-v2"
const RATE := 48000
const KERNELS := 8
const KERNEL_SECONDS := 0.3413333333333333
const KERNEL_LEAD := 0.0213333
const PAD := 2.0
const LOOKAHEAD := 0.014
const MASTER := 0.65
const ROOT := "res://assets/sounds/body_v2/"
const LOOP_SECONDS := 8.0
const LOOP_STAGGER := 0.731
const REF_DISTANCE := 4.0
const ROLLOFF := 1.2
const MAX_DISTANCE := 600.0
const SOUND_SPEED := 343.0
const DOPPLER := 0.3
const DEFAULT_CLANG_BALANCE_DB := 0.0
const SOURCE_HASHES := ${JSON.stringify(expected.hashes)}
`);
console.log('Exported byte-identical BODY V2 mono bank and lossless channel-routing copies.');
