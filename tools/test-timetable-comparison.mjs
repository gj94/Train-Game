import assert from 'node:assert/strict';
import {compareRuns} from './compare-timetable-runs.mjs';
const service=(priority,arrival_delay,departure=30000)=>({priority,arrival_delay,departure,stabled:true,max_wait_seconds:30});
const a={audit:{finished:3,ok:true,dispatcher:'classic'},services:{K1:service(20,360),B001:service(100,120),B002:service(75,300)}};
const b=structuredClone(a);b.audit.dispatcher='predictive';b.services.K1.arrival_delay=600;b.services.B001.arrival_delay=60;b.services.B002.arrival_delay=310;
const r=compareRuns(a,b);
assert.equal(r.matched,3);assert.equal(r.k1.change_seconds,240);
assert.equal(r.priority_groups[100].improved_over_15s,1);
assert.equal(r.priority_groups[75].within_15s,1);
assert.equal(r.priority_groups[20].worsened_over_15s,1);
assert.equal(r.largest_improvements[0].id,'B001');assert.equal(r.largest_regressions[0].id,'K1');
assert.equal(r.changed_departures.length,0);
const c=structuredClone(b);c.services.B001.departure+=600;
const authored=compareRuns(a,c);assert.deepEqual(authored.changed_departures,[{id:'B001',seconds:600}]);assert.match(authored.interpretation,/cannot be attributed/);
const mismatch=structuredClone(b);mismatch.services.B002.priority=90;assert.throws(()=>compareRuns(a,mismatch),/Priority changed/);
const unfinished=structuredClone(b);unfinished.audit.finished=2;assert.throws(()=>compareRuns(a,unfinished),/Incomplete/);
const unstabled=structuredClone(b);unstabled.services.K1.stabled=false;assert.throws(()=>compareRuns(a,unstabled),/did not clear/);
const missing=structuredClone(b);missing.services.K1.arrival_delay=-1;assert.throws(()=>compareRuns(a,missing),/no destination/);
const replaced=structuredClone(b);replaced.services.NEW=replaced.services.B002;delete replaced.services.B002;
assert.deepEqual(compareRuns(a,replaced).unmatched,{before:['B002'],after:['NEW']});
const identical=compareRuns(a,a);assert.equal(identical.largest_improvements.length,0);assert.equal(identical.largest_regressions.length,0);
assert.equal(identical.priority_groups[75].total_change_seconds,0);
console.log('18 timetable comparison assertions passed');
